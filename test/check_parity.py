"""Independent Python check of Julia/Python valuation parity.

Reads test/fixtures/valuation_parity.json (generated by the Julia package
through examples/make_results.jl), rebuilds every cash-flow schedule from
the instrument terms alone, and recomputes prices and yields with the
documented formulas:

- year fraction: actual days / 365
- price: sum of amount / (1 + y/m) ** (m * t), nominal annual yield y
  compounded m times per year
- yield: bisection on [-0.99, 5.0] to a bracket width of 1e-12

Parity bar (Stage 3 V3 sukuklab P0/5 acceptance): absolute price error
at most 1e-8 per 1,000 face; the same bound is applied to yields and to
schedule amounts (schedule amounts are exact decimal arithmetic in both
implementations, so they must agree far more tightly).

Standard library only. Exit code 0 on parity, 1 on any mismatch.
"""

import json
import sys
from datetime import date, timedelta
from pathlib import Path

FIXTURE = Path(__file__).parent / "fixtures" / "valuation_parity.json"
TOL = 1e-8


def parse(d):
    return date.fromisoformat(d)


def add_months(d, months):
    total = d.year * 12 + (d.month - 1) + months
    year, month0 = divmod(total, 12)
    month = month0 + 1
    # Day clamping mirrors Julia's Dates month arithmetic.
    if month == 12:
        next_first = date(year + 1, 1, 1)
    else:
        next_first = date(year, month + 1, 1)
    last_day = (next_first - timedelta(days=1)).day
    return date(year, month, min(d.day, last_day))


def distribution_dates(issue, maturity, freq):
    step = 12 // freq
    dates = []
    d = add_months(issue, step)
    while d < maturity:
        dates.append(d)
        d = add_months(d, step)
    dates.append(maturity)
    return dates


def payment_schedule(face, rate, issue, maturity, freq, amortizing):
    dates = distribution_dates(issue, maturity, freq)
    if amortizing:
        total = face * (1 + rate * (maturity - issue).days / 365)
        installment = total / len(dates)
        return [(d, installment) for d in dates]
    dist = face * rate / freq
    cfs = [(d, dist) for d in dates]
    cfs[-1] = (dates[-1], dist + face)
    return cfs


def price_from_cashflows(cfs, y, anchor, m):
    pv = 0.0
    for d, amount in cfs:
        t = (d - anchor).days / 365
        pv += amount / (1 + y / m) ** (m * t)
    return pv


def ytm_from_price(cfs, price, anchor, m):
    if price <= 0:
        return float("nan")

    def f(y):
        return price_from_cashflows(cfs, y, anchor, m) - price

    lo, hi = -0.99, 5.0
    flo, fhi = f(lo), f(hi)
    if (flo < 0) == (fhi < 0):
        return float("nan")
    for _ in range(200):
        mid = (lo + hi) / 2
        fmid = f(mid)
        if (fmid < 0) == (flo < 0):
            lo, flo = mid, fmid
        else:
            hi = mid
        if hi - lo < 1e-12:
            break
    return (lo + hi) / 2


def main():
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    failures = []

    def check(label, mine, theirs, tol=TOL):
        if abs(mine - theirs) > tol:
            failures.append(
                f"{label}: python {mine!r} vs julia {theirs!r} "
                f"(diff {abs(mine - theirs):.3e} > {tol:.0e})"
            )

    for name, case in data["cases"].items():
        issue = parse(case["issue"])
        maturity = parse(case["maturity"])
        anchor = parse(case["anchor"])
        m = case["m"]
        cfs = payment_schedule(
            case["face"], case["profit_rate"], issue, maturity,
            case["freq"], case["amortizing"],
        )
        stored = [(parse(d), a) for d, a in case["cashflows"]]
        # Only cash flows strictly after the anchor are valued.
        cfs = [(d, a) for d, a in cfs if d > anchor]
        if len(cfs) != len(stored):
            failures.append(
                f"{name}: schedule length python {len(cfs)} "
                f"vs julia {len(stored)}"
            )
            continue
        for (d1, a1), (d2, a2) in zip(cfs, stored):
            if d1 != d2:
                failures.append(f"{name}: date python {d1} vs julia {d2}")
            check(f"{name} amount on {d1}", a1, a2)
        for chk in case["price_checks"]:
            mine = price_from_cashflows(cfs, chk["yield"], anchor, m)
            check(f"{name} price at yield {chk['yield']}", mine, chk["price"])
        for chk in case["ytm_checks"]:
            mine = ytm_from_price(cfs, chk["price"], anchor, m)
            check(f"{name} ytm at price {chk['price']}", mine, chk["ytm"])

    if failures:
        print("PARITY FAIL")
        for f in failures:
            print(" -", f)
        return 1
    print(f"PARITY OK: {len(data['cases'])} cases within {TOL:.0e} "
          "per 1,000 face")
    return 0


if __name__ == "__main__":
    sys.exit(main())
